CREATE TABLE groups
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name                VARCHAR(255)                            NOT NULL,
    description         VARCHAR(255)                            NOT NULL,
    group_creation_date TIMESTAMP                               NOT NULL,
    group_end_date      TIMESTAMP                               NOT NULL,
    overseer_id         VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_groups PRIMARY KEY (id)
);

ALTER TABLE groups
    ADD CONSTRAINT FK_GROUPS_ON_OVERSEER FOREIGN KEY (overseer_id) REFERENCES overseers (id);

CREATE TABLE group_memberships
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    group_id        BIGINT                                  NOT NULL,
    group_member_id VARCHAR(255)                            NOT NULL,
    CONSTRAINT pk_group_memberships PRIMARY KEY (id)
);

